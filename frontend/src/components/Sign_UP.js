


import React, { useEffect, useState } from "react";

 import { useNavigate } from "react-router-dom";
 
  import "./SignUp.css";
   
  const SignUp = () => { 
    const [name, setName] = useState("");
     
    const [email, setEmail] = useState("");
     const [password, setPassword] = useState("");
     const navigate = useNavigate();
     useEffect(() => { const auth = localStorage.getItem("user");
       if (auth) { navigate("/signup");
      
     } }, [navigate]);
       const collectData = async () => { try { console.log(name, email, password);
       const response = await fetch("http://localhost:50334/register", {
         method: "POST",
          headers: { "Content-Type": "application/json", },
           body: JSON.stringify({ name, email, password }), });
       if (!response.ok) { 
        throw new Error("Server error");
      
     } const result = await response.json();
       console.log(result);
       localStorage.setItem("user", JSON.stringify(result.result));
       localStorage.setItem("token", JSON.stringify(result.auth));
     
navigate("/signup");
       
       
     } catch (error) { console.error("Error:", error);
       alert("Registration failed. Check backend & console.");
      
     } }
     return (<div className="signup-container">
       <div className="signup-card">
         <center>
           <table> 
            <tr> 
              <td>Username</td>
               <td> <input type="text" placeholder="Enter Username" onChange={(e) => setName(e.target.value)} /> 
               </td>
                </tr> 
                <tr> <td>Email</td>
                 <td> <input type="email" placeholder="Enter Email" onChange={(e) => setEmail(e.target.value)} /> </td>
                  </tr> 
                  <tr> <td>Password</td> <td> <input type="password" placeholder="Enter Password" onChange={(e) => setPassword(e.target.value)} /> </td> </tr>
                   <tr> <td colSpan="2"> <a href='/login'>Already Registered?</a> <input type="button" value="Sign Up" onClick={collectData} /> </td> </tr>
                    </table> </center> 
                    </div> 
                    </div>)
     }
     export default SignUp
    
















































































































































































































































































































































































































































